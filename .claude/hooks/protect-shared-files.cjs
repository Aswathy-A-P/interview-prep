#!/usr/bin/env node
'use strict';

const path = require('path');

const { readPayload, block, allow } = require('./_util.cjs');

const GUARDED_MATCHES = new Set(['full', 'generated', 'common']);
const WHOLE_FILE_TOOL = 'Write';
const EDIT_TOOL = 'Edit';
const PROJECT_SECTION = '## Project-specific';
const SIBLINGS = '.claude/conventions/sibling-repos.md';
const MANIFEST = '.claude/harness/manifest.json';

function repoRoot() {
  return process.env.CLAUDE_PROJECT_DIR || path.resolve(__dirname, '..', '..');
}

function sharedFiles() {
  try {
    return require('../harness/shared-files.cjs');
  } catch {
    return null;
  }
}

function editedPath(payload) {
  const input = payload.tool_input || {};
  return String(input.file_path || input.path || input.notebook_path || '');
}

function relativeToRepo(root, cwd, target) {
  if (!target) return null;
  const absolute = path.resolve(cwd, target.replace(/\\/g, '/'));
  const relative = path.relative(root, absolute).split(path.sep).join('/');
  if (!relative || relative === '..' || relative.startsWith('../') || path.isAbsolute(relative)) return null;
  return relative;
}

function textAfterEdit(payload, current) {
  const input = payload.tool_input || {};
  if ((payload.tool_name || '') === WHOLE_FILE_TOOL) return String(input.content || '');
  if ((payload.tool_name || '') !== EDIT_TOOL) return null;
  const before = String(input.old_string || '');
  const after = String(input.new_string || '');
  if (!current.includes(before)) return current;
  return input.replace_all ? current.split(before).join(after) : current.replace(before, after);
}

function changesCommonSection(shared, payload, root, rel) {
  let current;
  try {
    current = shared.readFile(root, rel);
  } catch {
    return true;
  }
  const proposed = textAfterEdit(payload, current);
  if (proposed === null) return true;
  const was = shared.splitProjectSection(current);
  const now = shared.splitProjectSection(proposed);
  if (!was || !now) return true;
  return was.common !== now.common;
}

function refusal(rel, match) {
  const source =
    `Take the change to the shared set, where it is made once and reaches every repo; ` +
    `${SIBLINGS} records where that repo sits.`;
  if (match === 'common') {
    return (
      `${rel} comes from the shared harness set, and this change falls above its ` +
      `"${PROJECT_SECTION}" heading, which is the only part of it this repo owns. The next install ` +
      `overwrites everything above that heading, so a change made here is lost. ${source}`
    );
  }
  if (match === 'generated') {
    return (
      `${rel} is generated by the shared harness set and copied out unedited, so a change made here ` +
      `is lost at the next install. Change what it is generated from instead. ${source}`
    );
  }
  return (
    `${rel} comes from the shared harness set and is byte-identical in every repo, so the next ` +
    `install overwrites a change made here and the work is lost. ${source} ` +
    `${MANIFEST} records which files are shared and which are this repo's own.`
  );
}

(async () => {
  const payload = await readPayload();
  const shared = sharedFiles();
  if (!shared) return allow();

  const root = repoRoot();
  if (!shared.exists(root, shared.MANIFEST) || shared.isSourceRepo(root)) return allow();

  const rel = relativeToRepo(root, payload.cwd || process.cwd(), editedPath(payload));
  if (!rel) return allow();

  let manifest;
  try {
    manifest = shared.loadManifest(root);
  } catch {
    return allow();
  }

  const entry = manifest.files[rel];
  if (!entry || !GUARDED_MATCHES.has(entry.match)) return allow();
  if (entry.match === 'common' && !changesCommonSection(shared, payload, root, rel)) return allow();

  return block(refusal(rel, entry.match));
})();
